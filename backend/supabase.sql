-- Cadastro Municipal de Artistas - Banco de Dados
-- Execute este script no SQL Editor do Supabase

DROP TABLE IF EXISTS artistas CASCADE;

CREATE TABLE artistas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  nome_artistico TEXT,
  cpf_cnpj TEXT,
  email TEXT NOT NULL,
  contato TEXT,
  cidade TEXT DEFAULT 'Bagé',
  area_atuacao TEXT NOT NULL,
  bio TEXT,
  tags TEXT[] DEFAULT '{}',
  disponibilidade TEXT[] DEFAULT '{}',
  foto_url TEXT,
  instagram TEXT,
  site TEXT,
  status TEXT DEFAULT 'Pendente' CHECK (status IN ('Pendente', 'Aprovado', 'Rejeitado')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Módulo de Feedback do Público
DROP TABLE IF EXISTS feedbacks CASCADE;

CREATE TABLE feedbacks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT,
  email TEXT,
  tipo TEXT DEFAULT 'Sugestão' CHECK (tipo IN ('Elogio', 'Sugestão', 'Crítica', 'Outro')),
  nota INTEGER CHECK (nota BETWEEN 1 AND 5),
  mensagem TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Políticas de Acesso (Desativa RLS para permitir inserção/leitura via API)
ALTER TABLE artistas DISABLE ROW LEVEL SECURITY;
ALTER TABLE feedbacks DISABLE ROW LEVEL SECURITY;

